T = json.load(open('text.json'))
P = {r['n']: r for r in T['pian']}

for n, pi, anchor, add in SUPPLY:
    para = P[n]['paras'][pi]
    flat = ''.join(t for k, t in para)
    assert anchor in flat, (n, anchor)
    end = flat.index(anchor) + len(anchor)
    # split the run list at `end`
    head, tail, pos = [], [], 0
    for k, t in para:
        if pos + len(t) <= end: head.append([k, t])
        elif pos >= end: tail.append([k, t])
        else:
            cut = end - pos
            head.append([k, t[:cut]]); tail.append([k, t[cut:]])
        pos += len(t)
    merged = head + [[k, t] for k, t in add] + tail
    # coalesce neighbouring runs of the same kind
    out = []
    for k, t in merged:
        if out and out[-1][0] == k: out[-1][1] += t
        else: out.append([k, t])
    P[n]['paras'][pi] = out
    print('補 %d/%d %d字' % (n, pi, sum(len(t) for k, t in add)))

json.dump(T, open('text.json', 'w'), ensure_ascii=False, indent=1)
