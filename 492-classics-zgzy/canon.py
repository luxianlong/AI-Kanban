def main():
    B = json.load(open('base.json'))
    log = {'glyph': [], 'simp': [], 'form': [], 'fix': []}

    def sweep(s, table, bucket):
        for a, b in table:
            if a in s:
                log[bucket].append((a, b, s.count(a)))
                s = s.replace(a, b)
        return s

    for q in B['pian']:
        q['paras'] = [sweep(p, GLYPH + SIMP + FORM, 'simp') for p in q['paras']]
    B['xu'] = sweep(B['xu'], GLYPH + SIMP + FORM, 'simp')

    hit = {n: 0 for n, *_ in FIX}
    for q in B['pian']:
        for i, p in enumerate(q['paras']):
            for n, a, b, why in FIX:
                if q['n'] == n and a in p:
                    q['paras'][i] = p = p.replace(a, b)
                    hit[n] += 1
    miss = [(n, a) for n, a, b, w in FIX
            if not any(b in p for q in B['pian'] if q['n'] == n for p in q['paras'])]
    if miss:
        raise SystemExit('改字が當たらない：%r' % miss)

    # 段の界と續きの標（底本の「:」）を分けて持つ
    for q in B['pian']:
        q['cont'] = [p.startswith(':') for p in q['paras']]
        q['paras'] = [p.lstrip(':').strip() for p in q['paras']]

    B['fix'] = [{'pian': n, 'from': a, 'to': b, 'why': w} for n, a, b, w in FIX]
    json.dump(B, open('canon.json', 'w'), ensure_ascii=False, indent=1)
    c = {}
    for a, b, n in log['simp']:
        c[(a, b)] = c.get((a, b), 0) + n
    print('缺字・符號 %d 處、簡體の紛れと字形 %d 處、改字 %d 處'
          % (sum(v for (a, b), v in c.items() if (a, b) in GLYPH),
             sum(v for (a, b), v in c.items() if (a, b) not in GLYPH),
             len(FIX)))
    for (a, b), n in sorted(c.items(), key=lambda x: -x[1]):
        print('   %s → %s ×%d' % (a, b, n))


if __name__ == '__main__':
    main()
