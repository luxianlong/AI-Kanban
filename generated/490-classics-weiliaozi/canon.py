# -*- coding: utf-8 -*-
"""底本（四庫全書文淵閣本）の誤りを直して canon.json を出す。

<b>改字の例はこの三つをすべて滿たすときだけ</b>——

  一、上海圖書館藏の白文刊本が底本と異なる（書影で一字ずつ目驗した。
      locate.py が葉を出す）。この本子は四庫の系統に屬さない。
  二、底本の文が通らない——義をなさないか、この書の他の箇所と矛盾する。
  三、<b>《羣書治要》（貞觀五年、六三一）の抄がその讀みを支持する</b>。
      今傳わるどの本子よりも四百年古い證人である。

二處しかない。<b>「刊本が底本と異なる」だけでは改めない。</b>
この刊本は上手な本ではなく、〈制談〉の「一夫仗劒擊于市」を
「一武伏劒擊於市」に作るような誤りがある（これも書影で見た）。
底本の文が通るところは底本のままとし、その段の註釋に出校する。

<b>《羣書治要》の讀みは本文に入れない。</b>治要の尉繚子は今本と系統が
違い、今本に無い句を多く持ち、逐字の一致は四割から六割しかない
（qszy.py を見よ）。それは「異文」ではなく別の本であって、
一句ずつ拾って今本に嵌めるのは校勘ではなく改作である。
治要の讀みは註と卷末に出す。
"""
import json, os

D = os.path.dirname(os.path.abspath(__file__))

# (篇, 底本, 改めた形, 據るところ)
FIX = [
 ('天官', '黄帝形德可以百勝', '黄帝刑德可以百勝',
  '上海圖書館本は「刑」に作る（封面の第三行に見えている）。'
  '治要も「吾聞黃帝有刑德」。答が「刑以伐之、德以守之」と'
  '刑と德を分けて説くのだから、問も「刑德」でなければ通らない。'
  '漢志の兵陰陽家を「推刑德、隨斗擊」と説くのも同じ「刑德」である'),
 ('戰威', '故戰者心本乎率身', '故戰者必本乎率身',
  '上海圖書館本は「必」に作る（同じ葉の隣の行の「民必先禮信」と'
  '同じ字形）。治要も「古爲戰者、必本氣以厲志」。'
  '「戰者心本乎率身」は語をなさず、しかも直後に'
  '「如心之使四肢也」と「心」が出るので重なる'),
]


def main():
    base = json.load(open(f'{D}/base.json', encoding='utf-8'))
    n = 0
    for j in base:
        for p in j['pian']:
            for pian, old, new, why in FIX:
                if pian != p['pian']:
                    continue
                hits = sum(x.count(old) for x in p['paras'])
                assert hits == 1, f'〈{pian}〉「{old}」が {hits} 箇所'
                for i, x in enumerate(p['paras']):
                    if old in x:
                        p['paras'][i] = x.replace(old, new, 1)
                        print('  〈%s〉%d  「%s」→「%s」' % (pian, i + 1, old, new))
                        print('        %s' % why)
                n += 1
    json.dump(base, open(f'{D}/canon.json', 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print('本文を改めたのは', n, '處（例に合う二處のみ）')
    assert n == len(FIX)


if __name__ == '__main__':
    main()
