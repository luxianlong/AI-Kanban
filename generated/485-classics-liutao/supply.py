# -*- coding: utf-8 -*-
"""底本脫去的兩處，據景宋本與四庫本補足；另改正三處形訛。改後寫回 canon.json。

補的兩處都是「兩個各自獨立的舊本都有、只有底本沒有」，不是孤證：

  《三疑第十七》 脫「民如牛馬」四字，又「餧」訛作「衣」。
      底本：惠施於民，必無愛財，數衣食之，從而愛之。
      兩本：惠施於民，必無愛財，民如牛馬，數餧食之，從而愛之。
      （景宋本「愛財」作「憂財」，四庫本同底本作「愛財」，從二本之同。）

  《烏雲澤兵第四十八》 脫一問一答共五十字。底本自「吾三軍敗而走。為之奈何？」
      徑接「太公曰：如此者，分為衝陣」，中間少了太公答「求途之道」一節與
      武王再問「敵人知我伏兵」一節——少了這一段，下文「須其畢出，發我伏兵」
      所待的「別將分隊以踰於水」就沒有著落。

標點為本頁所加。
"""
import json

FIX = [
    # (篇, 底本原文, 改正之後, 說明)
    (17, '必無愛財，數衣食之，從而愛之。',
         '必無愛財，民如牛馬，數餧食之，從而愛之。', '補四字、改一字'),
    (48, '吾三軍敗而走。為之奈何？」太公曰：「如此者，分為衝陣，',
         '吾三軍敗而走。為之奈何？」太公曰：「求途之道，金玉為主，'
         '必因敵使，精微為寶。」武王曰：「敵人知我伏兵，大軍不肯濟，'
         '別將分隊以踰於水，吾三軍大恐。為之奈何？」'
         '太公曰：「如此者，分為衝陣，', '補五十字'),
    # 形訛三處，兩本並不誤
    (18, '使冒難攻鈗', '使冒難攻銳', '鈗為銳之形訛'),
    (60, '均置蒺莉', '均置蒺藜', '莉為藜之形訛（同篇上文正作蒺藜）'),
    (13, '暴虐殘疾', '暴虐殘賊', '疾為賊之形訛'),
]


def main():
    d = json.load(open('canon.json'))
    P = {p['n']: p for p in d['pian']}
    added = 0
    for n, a, b, why in FIX:
        t = P[n]['text']
        if a not in t:
            raise SystemExit('《%s》對不上：%s' % (P[n]['title'], a))
        P[n]['text'] = t.replace(a, b, 1)
        added += len(b) - len(a)
        print('%-10s %s' % (P[n]['title'], why))
    json.dump(d, open('canon.json', 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print('淨增', added, '字（含標點）')


if __name__ == '__main__':
    main()
