def apply(s, pairs):
    for a, b in pairs:
        s = s.replace(a, b)
    return s


def main():
    B = json.load(open('base.json'))
    used = {i: 0 for i in range(len(EDITS))}
    for q in B['pian']:
        q['paras'] = [apply(p, PUNCT) for p in q['paras']]
        q['paras'] = [apply(p, FORM) for p in q['paras']]
        for pian, old, new in MEND:
            if pian == q['name']:
                assert sum(p.count(old) for p in q['paras']) == 1, old
                q['paras'] = [p.replace(old, new) for p in q['paras']]
        for i, (pian, old, new, why) in enumerate(EDITS):
            if pian != q['name']:
                continue
            hit = sum(p.count(old) for p in q['paras'])
            assert hit == 1, '「%s」が %d 處（一處でなければならぬ）' % (old, hit)
            used[i] += 1
            q['paras'] = [p.replace(old, new) for p in q['paras']]
    assert all(v == 1 for v in used.values()), used
    json.dump(B, open('canon.json', 'w'), ensure_ascii=False, indent=1)
    print('改字 %d 處、字形の統一 %d 對、句讀の正規化 %d 對・繕い %d 處'
          % (len(EDITS), len(FORM), len(PUNCT), len(MEND)))


if __name__ == '__main__':
    main()
