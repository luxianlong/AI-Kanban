# -*- coding: utf-8 -*-
"""底本の誤りを直して canon.json を出す。

<b>改字の例はこの三つをすべて滿たすときだけ</b>——

  一、上海圖書館藏の白文刊本と四庫全書本が一致して底本と異なる
      （刊本は書影で一つ一つ目驗した。locate.py が葉を出す）。
  二、底本の文が通らない——義をなさないか、この書の他の箇所と矛盾する。
  三、外證がある。引かれている原書（孫子・司馬法・尉繚子・國語・左傳・
      史記・晉書）か、この書自身の内證。

十二處ある。<b>「二本が一致して底本と異なる」だけでは改めない。</b>
底本の文が通るところは底本のままとし、その段の註釋に出校する——たとえば
《司馬法》を引く「天下雖平，忘戰必危」は、四庫本が「雖安」に作り、
《司馬法》の原文も「安」であるが、上海圖書館本は底本と同じく「平」に作る。
四庫の館臣が原書に合わせて直したのであろう。本頁は底本に從う。
（この一條のために刊本を見た甲斐があった——書影が無ければ「安」に
改めていたはずである。）
"""
import json, os

D = os.path.dirname(os.path.abspath(__file__))

# (卷, 底本, 改めた形, 據った外證)
FIX = [
 ('卷上', '晉馬隆計涼州', '晉馬隆討涼州',
  '晉書馬隆傳。馬隆は涼州を「討」ったのであって「計」ったのではない'),
 ('卷上', '莫能出其鬪閾', '莫能出其閫閾',
  '「閫閾」は敷居、轉じて範圍。「鬪閾」は語をなさない'),
 ('卷上', '十軌無里', '十軌為里',
  '國語齊語「十軌為里」。上下も「五家為軌」「四里為連」と續く'),
 ('卷上', '齊桓有昭陵之師', '齊桓有召陵之師',
  '左傳僖公四年の召陵の師。昭陵は太宗自身の陵で、その前で言う語ではない'),
 ('卷上', '此大率孫、吳之舊法也', '此大率荀吳之舊法也',
  '同じ段の冒頭が「荀吳用車法爾」。荀吳（晉の荀吳）を承ける'),
 ('卷上', '不貴於人', '不責於人',
  '孫子勢篇「求之於勢、不責於人」'),
 ('卷上', '臣前曾部蕃漢', '臣前曾述蕃漢',
  '「曾部」は語をなさない。前の卷で述べた事を承ける'),
 ('卷中', '〈束武令〉', '〈束伍令〉',
  '尉繚子の篇名は〈束伍令〉。上下も「五人為伍」「尺籍伍符」と伍を言う'),
 ('卷中', '方生於正', '方生於步',
  '直後が「方所以矩其步、圓所以綴其旋」'),
 ('卷中', '皆起於度量方國也', '皆起於度量方圓也',
  '前段來この一段は方と圓を言う。「方國」は語をなさない'),
 ('卷中', '勢加彍弩', '勢如彍弩',
  '孫子勢篇「勢如彍弩、節如發機」。下句の「節如發機」は底本も正しい'),
 ('卷下', '徒謂空文', '徒誦空文',
  '卷中に「但誦空文、鮮克推廣其義」とある'),
]

# 字形・用字を一つに揃える（語は變えない）。底本のなかで揺れているもの。
UNIFY = [('臣按《尉繚子》', '臣案《尉繚子》'),      # 底本は案 18・按 1
         ('〈史記．穰苴傳〉', '《史記·穰苴傳》')]   # 書名なので《》、中黑も揃える

PUNCT = [('︰', '：'), ('“', '「'), ('”', '」')]


def main():
    base = json.load(open(f'{D}/base.json', encoding='utf-8'))
    n = 0
    for j in base:
        paras = j['paras']
        for juan, old, new, why in FIX:
            if juan != j['name']:
                continue
            hits = sum(p.count(old) for p in paras)
            assert hits == 1, f'{juan}「{old}」が {hits} 箇所'
            for i, p in enumerate(paras):
                if old in p:
                    paras[i] = p.replace(old, new, 1)
                    print('  %s %2d  「%s」→「%s」　%s'
                          % (juan, i + 1, old, new, why))
            n += 1
        for group in (UNIFY, PUNCT):
            for old, new in group:
                for i, p in enumerate(paras):
                    if old in p:
                        paras[i] = p.replace(old, new)

    json.dump(base, open(f'{D}/canon.json', 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print('本文を改めたのは', n, '處（例に合う十二處のみ）')
    assert n == len(FIX)


if __name__ == '__main__':
    main()
